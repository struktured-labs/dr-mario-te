#!/usr/bin/env python3
"""Emit RESULTS.md from results.json.

Every number AND every causal sentence in the output is a function of the measured
values. Nothing about the mechanism, the direction, or the regime is hardcoded --
that is the corollary to measurement-rules #25: numbers get recomputed, the prose
explaining them does not, so explanatory text that names a cause must be driven
entirely by what was measured or it will outlive the regime it was written for.
"""
from __future__ import annotations

import json
import sys

CLAIM_HI, CLAIM_LO, CLAIM_P = 6.00, 0.67, 0.0215


def pct(x):
    return "n/a" if x != x else f"{100*x:.2f}%"


def main(path, out):
    R = json.load(open(path))
    m, a = R.get("mirror"), R.get("adv")
    L = []
    w = L.append

    w("# RESULTS — task #80, side asymmetry in the kill channel\n")
    w("Generated by `make_report.py` from `results.json`. Verdicts are whatever the\n"
      "pre-registered decision rule in `analyze_side_asym.py` returned; they were\n"
      "committed in `PREREG.md` (056934a) before any arm ran.\n")

    # ---------------------------------------------------------------- gates first
    w("\n## Gates\n")
    for tag in ("adv", "mirror"):
        g = R.get(f"mutant_gate_{tag}")
        if g:
            w(f"- **{tag} side-counter killed mutant**: "
              f"{'PASS' if g['pass'] else '**FAIL**'} — base deaths by side "
              f"{g['base'][0]}/{g['base'][1]}, mutant {g['mutant'][0]}/{g['mutant'][1]} "
              f"({'exchanged exactly' if g['deaths_exchanged'] else 'NOT exchanged'}).")
    w("- verdict-script + counter gates: see `out/gate.txt` (24/24 before launch, "
      "incl. an inert counter the gate must reject).")

    # -------------------------------------------------------------- primary arm
    if a:
        w("\n## PRIMARY endpoint — champion death rate by the champion's seat "
          "(champion vs evolved adversary)\n")
        w(f"n = {a['n_seeds']} seeds ({a['n_games']} games). "
          f"Total champion deaths: **{a['total_deaths']}**.\n")
        w("| seat | deaths | rate |")
        w("|---|---|---|")
        w(f"| 0 (moves first) | {a['deaths_side0']} | {pct(a['rate_side0'])} |")
        w(f"| 1 (moves second) | {a['deaths_side1']} | {pct(a['rate_side1'])} |")
        ci = a["delta_ci_pp"]
        w(f"\nΔ = **{a['delta_pp']:+.2f} pp** (seat 0 − seat 1), "
          f"95% seed-clustered CI [{ci[0]:+.2f}, {ci[1]:+.2f}] pp. "
          f"Discordant seeds {a['discordant_b']} / {a['discordant_c']}, "
          f"exact McNemar **p = {a['mcnemar_p']:.4g}**.\n")
        w(f"### VERDICT: **{a['verdict']}**\n\n{a['verdict_reason']}\n")

        # cause-naming driven strictly by measured values
        if a["total_deaths"] == 0:
            w("\nThe arm produced no deaths at all, so it cannot express the "
              "quantity. This is not a symmetry result.")
        else:
            hi = max(a["rate_side0"], a["rate_side1"])
            lo = min(a["rate_side0"], a["rate_side1"])
            ratio = hi / lo if lo > 0 else float("inf")
            worse = 0 if a["rate_side0"] >= a["rate_side1"] else 1
            w(f"\nObserved ratio {ratio:.2f}x, worse seat = **{worse}**. "
              f"The claim under test was {CLAIM_HI}% vs {CLAIM_LO}% "
              f"(ratio {CLAIM_HI/CLAIM_LO:.1f}x, p={CLAIM_P}).")
            half = (ci[1] - ci[0]) / 2
            w(f"The interval half-width is {half:.2f} pp against a claimed effect of "
              f"{CLAIM_HI - CLAIM_LO:.2f} pp "
              f"({(CLAIM_HI - CLAIM_LO)/half:.1f}x the resolution of this measurement).")

    # --------------------------------------------------------------- mirror arm
    if m:
        w("\n## MECHANISM arm — champion vs champion, boards swapped between the "
          "two orientations of each seed\n")
        w(f"n = {m['n_seeds']} seeds ({m['n_games']} games), "
          f"{m['stall_games']} stalls.\n")
        lo, hi = m["win0_ci"]
        w(f"**P(seat 0 wins) = {m['win0_rate']:.4f}**, 95% seed-clustered CI "
          f"[{lo:.4f}, {hi:.4f}].  Under no positional effect this is 0.5 exactly, "
          f"because the board draw is exchanged between the two orientations.\n")
        sd, bd = m["seat_determined_seeds"], m["board_determined_seeds"]
        tot = sd + bd
        if tot:
            w(f"Decomposition: **{sd}** seeds where the same SEAT won both "
              f"orientations ({100*sd/tot:.1f}%), **{bd}** where the same BOARD won "
              f"both ({100*bd/tot:.1f}%). Under no positional effect and a purely "
              f"board-determined outcome the seat-determined count would be 0.\n")
        w(f"Deaths by physical seat: {m['deaths_side0']} at seat 0 vs "
          f"{m['deaths_side1']} at seat 1 (total {m['total_deaths']}); "
          f"seed-clustered P(death at seat 0) = {m['death0_rate']:.4f} "
          f"CI [{m['death0_ci'][0]:.4f}, {m['death0_ci'][1]:.4f}].\n")
        w(f"### VERDICT: **{m['verdict']}**\n\n{m['verdict_reason']}\n")

    # ------------------------------------------------------- population mutant
    sb = R.get("same_board")
    if sb:
        w("\n## Population mutant (`same_board`) — the registered mechanism test\n")
        w(f"Both seats forced onto one virus board, so the only thing separating "
          f"them is turn order. **Registered prediction: P(seat 0 wins) = 1.000.**\n")
        w(f"Measured: **P(seat 0 wins) = {sb['win0_rate']:.4f}** over "
          f"{sb['n_seeds']} seeds ({sb['n_games']} games).\n")
        if abs(sb["win0_rate"] - 1.0) < 1e-9:
            w("**Prediction met exactly.** In the exact-tie limit the harness's "
              "first-mover structure decides every game: seat 0 moves first in every "
              "round and its terminal condition is detected before seat 1 gets its "
              "move. The mechanism named in the prereg is real and isolated.")
        elif sb["win0_rate"] > 0.9:
            w("Prediction substantially met — the first-mover structure dominates "
              "the exact-tie limit, though not universally.")
        else:
            w("**PREDICTION NOT MET.** The first-mover mechanism named in the prereg "
              "does not decide the exact-tie limit, and is withdrawn as the "
              "explanation. What separates the seats under identical boards is "
              "unexplained and needs its own investigation.")

    w("\n## Scope — what this does NOT cover\n")
    w("Offline fast sim only; level 11; `max_pills` 300; garbage ON; the "
      "champion-vs-adversary and champion-vs-champion pairings only. No silicon or "
      "RTL claim. Nothing here transfers to human opponents. A mirror-arm finding is "
      "a statement about **this harness**; whether the ROM shares the same turn-order "
      "structure is a separate question and is not tested here.\n")

    open(out, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
