#!/usr/bin/env python3
"""WHOLE-SEARCH CHECK: the sim brain that STEER5b/5c measured (cascade_leaf5b_x, HSV w5[3] = 512, added AFTER the base
leaf's signed-16 wrap) vs an RTL-EXACT twin (the same module with every HSV addition wrapped to signed 16, i.e. the
term INSIDE the combine, as DRHSV implements it in LeafEval.sv). The twin is generated by a textual transform of the
four `+ _x5(...)` sites, so everything else is byte-for-byte the measured module.
If the two agree on every root decision, the RTL term reproduces the brain the holdout measured.
Boards: real gate-(b) play (fw540 baseline, owner model, couch steering off) + the reach corpus boards.
Usage: check_hsv_search.py [--games N]
"""
import argparse, os, re, sys, importlib.util
CVX = "/home/struktured/projects/dr-mario-h16-wt/experiments/cvx"
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
os.environ.setdefault("NUMBA_CACHE_DIR", os.path.join(ROOT, "tmp", "nbcache_hsvcheck"))
sys.path.insert(0, CVX)
import import_pin; import_pin.pin()
import numpy as np

SITES = [
    ("            lv += _x5(ccol, cvir, fl, w5)\n",
     "            lv = _w16(lv + _x5(ccol, cvir, fl, w5))\n"),
    ("        return (1, 0, 0, _combine_terms(terms, w) + _x5(ccol, cvir, fl, w5), 0)\n",
     "        return (1, 0, 0, _w16(_combine_terms(terms, w) + _x5(ccol, cvir, fl, w5)), 0)\n"),
    ("    val = _combine_terms(terms, w) + _x5(pcol, pvir, fl, w5)\n",
     "    val = _w16(_combine_terms(terms, w) + _x5(pcol, pvir, fl, w5))\n"),
    ("        tot += best3 if have3 else (_leafv_ship(b2c, b2v, w, fl) + _x5(b2c, b2v, fl, w5))\n",
     "        tot += best3 if have3 else _w16(_leafv_ship(b2c, b2v, w, fl) + _x5(b2c, b2v, fl, w5))\n"),
]
W16 = '''

@njit(cache=True, fastmath=False)
def _w16(x):
    """signed-16 wrap: the RTL combine's single wrap (modular, so wrap(wrap(a) + b) == wrap(a + b))."""
    y = x & 0xFFFF
    if y >= 0x8000:
        y -= 0x10000
    return int64(y)
'''


def make_rtl_module():
    src = open(os.path.join(CVX, "cascade_leaf5b_x.py")).read()
    n_all = len(re.findall(r"_x5\(", src))
    for a, b in SITES:
        assert src.count(a) == 1, a
        src = src.replace(a, b, 1)
    # insert _w16 before the first function that uses it (after _x5's definition)
    anchor = "@njit(cache=True, fastmath=False)\ndef _leaf_chain5("
    assert src.count(anchor) == 1
    src = src.replace(anchor, W16.lstrip("\n") + "\n\n" + anchor, 1)
    out = os.path.join(ROOT, "tmp", "cascade_leaf5b_rtl_x.py")
    open(out, "w").write(src)
    spec = importlib.util.spec_from_file_location("cascade_leaf5b_rtl_x", out)
    m = importlib.util.module_from_spec(spec); sys.modules["cascade_leaf5b_rtl_x"] = m; spec.loader.exec_module(m)
    return m, n_all


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--games", type=int, default=6)
    a = ap.parse_args()
    import cascade_leaf5b_x as L5
    import gate_b as G, bursty_model as BM, vs_race as V, fast_rtl_x as FX
    from drmario.faithful_game import Pill
    R, n_x5 = make_rtl_module()
    w, fl = FX.variant("winner")
    hsv = (0, 0, 0, 512)
    sim = L5.Leaf5ReachDecider(w, fl, w5=hsv, tap=2)
    rtl = R.Leaf5ReachDecider(w, fl, w5=hsv, tap=2)
    off = L5.Leaf5ReachDecider(w, fl, w5=(0, 0, 0, 0), tap=2)
    m = BM.fit_struktured_20260804(); boards = []
    base = V._decider("fw540")

    def choose(env, col, vir, ctx):
        boards.append((env.board.clone(), env.pills_placed, Pill(int(env.cur.a), int(env.cur.b)),
                       Pill(int(env.nxt.a), int(env.nxt.b))))
        return base(env, col, vir, ctx)
    for s in range(a.games):
        G.play(40001 + 2 * s, None, m, choose=choose)
    same = moved = 0; bad = []
    for i, (b, k, c, n) in enumerate(boards):
        x, y = sim.choose(b, c, n, k), rtl.choose(b, c, n, k)
        same += int(x == y)
        if x != y:
            bad.append(i)
        moved += int(x != off.choose(b, c, n, k))
    print(f"transform: {len(SITES)} HSV addition sites wrapped (of {n_x5} _x5 references incl. the def/calls)")
    print(f"boards {len(boards)} ({a.games} games): sim (post-wrap HSV) == RTL-exact (in-combine HSV) {same}/{len(boards)}; "
          f"HSV moved the root decision vs w5=0 on {moved}")
    if bad:
        print("  mismatches at", bad[:20])
    print("CHECK_HSV_SEARCH", "PASS" if same == len(boards) and moved > 0 else "FAIL")
    return 0 if same == len(boards) and moved > 0 else 1


if __name__ == "__main__":
    sys.exit(main())
