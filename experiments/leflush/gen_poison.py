#!/usr/bin/env python3
"""Generate poison.inc for sim_poison.cpp: the table of every LeafEval STATE register (+ the CoproDrMario engine-argument
registers and the slot RAM) that survives a copro GO reset, with C++ to poison any subset of them and to dump them.

Source of truth = the RTL: every `reg` declared in LeafEval.sv (module scope; named-block temporaries carry `__DOT__`
in their Verilator name and are skipped), intersected with the Verilator root header (so a reg that only exists under
an `ifdef` this build did not define is skipped, and a typo cannot silently drop one). Excluded, with the reason printed:
  RESET  the copro reset assigns it (LeafEval `if (rst)` arm, DRLEV_WRREG h_wr): the GO reset already makes it clean
  COMB   assigned in an always @* block (no state)
  WITNESS simulation-only invariant counters (`ifdef VERILATOR)
  LOOPVAR integer loop variables
Usage: gen_poison.py LeafEval.sv CoproDrMario.sv VCoproDrMario___024root.h OUT.inc"""
import re
import sys

RESET = {"st", "done", "sl_cpw", "base_mode", "delta_mode", "dv_fallback", "h_wr"}
COMB = {"bl_we", "bl_wa", "bl_wd"}
WITNESS = {"byp_fire", "byp_used", "dt_late"}
LOOPVAR = {"i", "di"}
# CoproDrMario: the engine argument / select registers (written by firmware stores, never by the reset) and the read
# pipeline register. lev_a_tgt is cleared by the copro reset (DRDIST) and is excluded as RESET.
COPRO_REGS = ["lev_wslot", "lev_a_o4", "lev_a_sl", "lev_a_ca", "lev_a_cb", "lev_a_col", "lev_a_fix", "lev_a_chw", "lev_q"]
COPRO_RESET = {"lev_a_tgt"}


def rtl_regs(path):
    names = []
    for line in open(path):
        s = re.sub(r"/\*.*?\*/", "", line.split("//")[0])
        for stmt in s.split(";"):                       # several `reg ...;` statements can share a line
            m = re.match(r"\s*(?:output\s+)?reg\s+(?:signed\s+)?(?:\[[^\]]+\]\s*)?(.*)$", stmt)
            if not m:
                continue
            for part in m.group(1).split(","):
                nm = re.match(r"\s*([A-Za-z_][A-Za-z0-9_]*)", part)
                if nm:
                    names.append(nm.group(1))
    return names


def header_members(path):
    mem = {}
    pat = re.compile(r"^\s*(VlUnpacked<(\w+)/\*(\d+):(\d+)\*/,\s*(\d+)>|VlWide<(\d+)>/\*(\d+):(\d+)\*/|(\w+)/\*(\d+):(\d+)\*/)"
                     r"\s+(CoproDrMario__DOT__\w+);")
    for line in open(path):
        m = pat.match(line)
        if not m:
            continue
        full = m.group(12)
        if m.group(2):
            mem[full] = ("arr", int(m.group(3)) - int(m.group(4)) + 1, int(m.group(5)))
        elif m.group(6):
            mem[full] = ("wide", int(m.group(7)) - int(m.group(8)) + 1, int(m.group(6)))
        else:
            mem[full] = ("scalar", int(m.group(10)) - int(m.group(11)) + 1, 1)
    return mem


def main():
    lev, cop, hdr, out = sys.argv[1:5]
    mem = header_members(hdr)
    P = "CoproDrMario__DOT__leafeval__DOT__"
    table, skipped = [], []
    seen = set()
    for n in rtl_regs(lev):
        if n in seen:
            continue
        seen.add(n)
        why = ("RESET" if n in RESET else "COMB" if n in COMB else "WITNESS" if n in WITNESS
               else "LOOPVAR" if n in LOOPVAR else None)
        if why:
            skipped.append((n, why)); continue
        if P + n not in mem:
            skipped.append((n, "NOT-IN-BUILD")); continue
        table.append((n, P + n) + mem[P + n])
    for n in ("q_a", "q_b"):
        table.append(("slotram.q_" + n[-1], P + "slotram__DOT__" + n) + mem[P + "slotram__DOT__" + n])
    table.append(("slotram.mem", P + "slotram__DOT__mem") + mem[P + "slotram__DOT__mem"])
    for n in COPRO_REGS:
        table.append((n, "CoproDrMario__DOT__" + n) + mem["CoproDrMario__DOT__" + n])
    for n in COPRO_RESET:
        skipped.append((n, "RESET"))
    # all-copro sanity: every CoproDrMario lev_ reg is either in COPRO_REGS, COPRO_RESET or a wire (not a reg)
    copro_regs = set(rtl_regs(cop))
    for n in sorted(copro_regs):
        if n.startswith("lev_") and n not in COPRO_REGS and n not in COPRO_RESET:
            raise SystemExit(f"unclassified CoproDrMario engine reg {n}")
    with open(out, "w") as f:
        f.write("// generated by gen_poison.py -- do not edit\n")
        f.write(f"static const int NPREG = {len(table)};\n")
        f.write("static const char* PREG_NAME[NPREG] = {" + ", ".join(f'"{t[0]}"' for t in table) + "};\n")
        f.write("static void preg_poison(VCoproDrMario___024root* r, int k, std::mt19937_64& g) {\n  switch (k) {\n")
        for k, (n, full, kind, w, cnt) in enumerate(table):
            mask = (1 << w) - 1 if w < 64 else (1 << 64) - 1
            if kind == "scalar":
                f.write(f"  case {k}: r->{full} = (g() & 0x{mask:x}ULL); break;\n")
            elif kind == "arr":
                f.write(f"  case {k}: for (int j = 0; j < {cnt}; j++) r->{full}[j] = (g() & 0x{mask:x}ULL); break;\n")
            else:
                f.write(f"  case {k}: for (int j = 0; j < {cnt}; j++) r->{full}[j] = (uint32_t)g(); break;\n")
        f.write("  }\n}\n")
        f.write("static bool preg_set(VCoproDrMario___024root* r, int k, unsigned long long v) {\n  switch (k) {\n")
        for k, (n, full, kind, w, cnt) in enumerate(table):
            if kind == "scalar":
                f.write(f"  case {k}: r->{full} = v; return true;\n")
        f.write("  }\n  return false;\n}\n")
        f.write("static void preg_dump(VCoproDrMario___024root* r, int k) {\n  switch (k) {\n")
        for k, (n, full, kind, w, cnt) in enumerate(table):
            if kind == "scalar":
                f.write(f"  case {k}: printf(\"%llx\", (unsigned long long)r->{full}); break;\n")
            elif kind == "arr":
                f.write(f"  case {k}: for (int j = 0; j < {cnt}; j++) printf(\"%x%s\", (unsigned)r->{full}[j], "
                        f"j + 1 < {cnt} ? \".\" : \"\"); break;\n")
            else:
                f.write(f"  case {k}: for (int j = {cnt} - 1; j >= 0; j--) printf(\"%08x\", (unsigned)r->{full}[j]); break;\n")
        f.write("  }\n}\n")
    print(f"{len(table)} poisonable registers -> {out}")
    for n, why in skipped:
        print(f"  skip {n:14s} {why}")


if __name__ == "__main__":
    main()
